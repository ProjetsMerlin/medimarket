import type { Metadata } from "next";
import type { ReactNode } from "react";

import "@/app/globals.css";
import "@/app/helper.css";

import { Navbar8 } from "@/app/components/navbar-08";
import { Footer8 } from "@/app/components/footer-08";
import CartDrawer from "@/app/components/cart/CartDrawer";
import CartProvider from "@/app/components/cart/CartProvider";
import Notifications from "@/app/components/cart/Notifications";
import { getCart } from "@/app/lib/cart";

export const metadata: Metadata = {
  title: "Medi-Market",
  description: "Generated by create next app",
};

type RootLayoutProps = {
  children: ReactNode;
};

export default async function RootLayout({ children }: RootLayoutProps) {
  const cart = await getCart();

  return (
    <html lang="fr-BE">
      <body className="antialiased">
        <CartProvider cart={cart}>
          <Navbar8 />
          {children}
          <Footer8 />
          <CartDrawer />
          <Notifications />
        </CartProvider>
      </body>
    </html>
  );
}